import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, rmSync, readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { createApp } from '../server.mjs';

test('management: protected overview, honest circle counts and additive samples persist after restart',async t=>{
  const base=resolve('.artifact-work');mkdirSync(base,{recursive:true});
  const dir=mkdtempSync(resolve(base,'management-')),dataFile=resolve(dir,'store.json');
  const adminKey='management-test-key-with-at-least-24-characters';
  let server,url;
  const start=async()=>{server=createApp({dataFile,adminKey});await new Promise(r=>server.listen(0,'127.0.0.1',r));url=`http://127.0.0.1:${server.address().port}`;};
  const stop=()=>new Promise(r=>{server.close(r);server.closeAllConnections();});
  t.after(async()=>{await stop();assert.ok(dir.startsWith(base+'\\'));rmSync(dir,{recursive:true,force:true});});
  await start();
  function client(){let cookie='';return async(path,body,status=200)=>{const r=await fetch(url+'/api'+path,{method:body===undefined?'GET':'POST',headers:{cookie,...(body===undefined?{}:{'Content-Type':'application/json','X-Requested-With':'CampusKindness'})},body:body===undefined?undefined:JSON.stringify(body)});if(r.headers.has('set-cookie')){assert.match(r.headers.get('set-cookie'),/HttpOnly; SameSite=Strict/);cookie=r.headers.get('set-cookie').split(';')[0];}const data=await r.json();assert.equal(r.status,status,JSON.stringify(data));return data;};}
  const visitor=client(),admin=client(),member=client();
  await visitor('/admin/overview',undefined,401);
  await visitor('/admin/samples',{},401);
  await visitor('/admin/login',{key:'wrong'},401);
  await visitor('/login',{userId:'lin'});
  await visitor('/admin/overview',undefined,401);
  const identity=await member('/identities',{name:'真实试用身份',avatar:'leaf'},201);
  await member('/me/circle',{schoolId:'whu',mode:'demo'});
  const original=(await member('/tasks',{title:'用户原来的学习求助',category:'study',mode:'online',deadline:new Date(Date.now()+86400000).toISOString()},201)).task;
  await admin('/admin/login',{key:adminKey});
  const first=await admin('/admin/overview');
  assert.equal(first.summary.realUsers,1);assert.equal(first.schools.find(s=>s.id==='whu').realCount,1);
  assert.equal(first.schools.find(s=>s.id==='whu').demoCount,0);
  assert.deepEqual(await admin('/admin/samples',{}),{usersAdded:28,tasksAdded:28});
  assert.deepEqual(await admin('/admin/samples',{}),{usersAdded:0,tasksAdded:0});
  const counts=(await visitor('/schools')).schools;
  assert.equal(counts.find(s=>s.id==='whu').memberCount,5);
  assert.equal(counts.find(s=>s.id==='whu').realCount,1);
  assert.equal(counts.find(s=>s.id==='whu').demoCount,4);
  assert.equal((await visitor('/demo-accounts')).accounts.length,3);
  await visitor('/login',{userId:'sample-whu-0'},403);
  await member('/tasks/sample-task-whu-0/action',{action:'respond',message:'测试'},409);
  const overview=await admin('/admin/overview'),projection=JSON.stringify(overview);
  assert.ok(!projection.includes('recoveryHash'));assert.ok(!projection.includes(identity.recoveryKey));assert.ok(!projection.includes(adminKey));
  assert.ok(!projection.includes('owned_ids'));assert.ok(!projection.includes('messages'));
  assert.ok(overview.tasks.some(t=>t.id===original.id));
  const saved=JSON.parse(readFileSync(dataFile,'utf8'));assert.equal(saved.tasks.find(t=>t.id===original.id).title,original.title);
  await stop();await start();
  assert.equal((await member('/me')).user.id,identity.user.id);
  assert.equal((await admin('/admin/overview')).summary.users,overview.summary.users);
  const fresh=client();await fresh('/identities/restore',{recoveryKey:identity.recoveryKey});
  assert.equal((await fresh('/tasks/'+original.id)).task.title,original.title);
  await admin('/admin/logout',{});await admin('/admin/overview',undefined,401);
  assert.equal((await fetch(url+'/admin')).status,200);
});
